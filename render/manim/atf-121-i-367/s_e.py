    lg = VGroup(*[Line([0, 0, 0], [0.8 * e, 0, 0], color=ROUGE_3, stroke_width=3 * e) for _ in range(3)]).arrange(DOWN, buff=0.13 * e).move_to(f.get_center() + np.array([0.2 * e, -0.15 * e, 0]))
